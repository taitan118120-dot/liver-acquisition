def find_source(text):
    """ユーザーの返答から流入元ラベルを判定。なければ None。"""
    t = text.strip().lower()
    # まず完全一致（番号のみの短い返答を優先）
    for label, keys in SOURCE_OPTIONS.items():
        for k in keys:
            if t == k.lower():
                return label
    # 次に部分一致
    for label, keys in SOURCE_OPTIONS.items():
        for k in keys:
            if k.lower() in t:
                return label
    return None

