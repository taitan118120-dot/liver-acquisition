_DATETIME_PATTERN = re.compile(
    r"\d{1,2}時|\d{1,2}:\d{2}|\d{1,2}/\d{1,2}|\d{1,2}月\d{1,2}日|\d{1,2}日|"
    r"明日|あした|あさって|明後日|今日|今晩|今夜|今週|来週|再来週|週末|平日|土日|"
    r"[月火水木金土日]曜|午前|午後|夜|昼|朝|夕方|深夜|いつでも|何時でも"
)


# 過去・習慣の言い方（「昨夜」「今朝」「毎晩」など）は希望日時ではない
_NOT_SLOT_WORDS_RE = re.compile(r"昨夜|昨晩|昨日|今朝|毎朝|毎晩|毎日|毎週|先日|前日")
# 日付や時刻まで入っている＝具体的な日時の提案
_CONCRETE_TIME_RE = re.compile(r"\d{1,2}\s*時|\d{1,2}:\d{2}|\d{1,2}/\d{1,2}|\d{1,2}月\d{1,2}日|\d{1,2}日")
_QUESTION_RE = re.compile(r"[？?]|ですか|でしょうか")


def classify_slot_reply(text, has_keyword=False):
    """日程を聞いたあとの返事を分類する

    "slot"     … 希望日時として受け付ける（「本日22時は如何でしょうか？」のような提案も含む）
    "question" … 具体的な日時なしの相談（「夜でも大丈夫ですか？」）。受け付けずに聞き直す
    None       … 日時の話ではない。キーワード応答などへ流す
    has_keyword は「収入」等の自動応答キーワードを含むか。日時が曖昧なら質問を優先する
    （「収入は夜の配信でも変わりますか」を日程として受け付けないため）。
    """
    t = _NOT_SLOT_WORDS_RE.sub(" ", text.strip())
    if not _DATETIME_PATTERN.search(t):
        return None
    if _CONCRETE_TIME_RE.search(t):
        return "slot"
    if has_keyword:
        return None
    if _QUESTION_RE.search(t):
        return "question"
    return "slot"


