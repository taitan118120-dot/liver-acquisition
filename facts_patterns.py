#   - 少額表記 … ライバーの収入目安には月15万の下限があるが、
#     **代理店パートナーの報酬**（LPが正本: 1ヶ月目 月5万円〜）は別の主語で、
#     フリー対比の少額も意図的に維持することがある [[project_taitan_pro_note_facts]]
#   - 実績誇張 … 「静かに消えていく人を何百人も見てきた」は輩出実績の主張ではなく
#     代表の見聞。ただし裏の取れない数字ではあるので、消すかは人が決める話
#   - 他社比較 … LPの比較表は訴求の骨格。書き換えは文言の設計判断になる
#
# これらを赤にすると番犬が永久に鳴きやまなくなる（[[feedback_watchdog_autoclose]]）。
# **検知はする／赤にはしない（WARN）** で切り分け、判断を人に返す。
# 生成側の検品はこの集合を参照しないので、新しく書く文章では今までどおり全部NG。
AUDIT_WARN_LABELS = frozenset({
    # money_violations() が組み立てるラベルと同じ式で作る（直書きすると
    # MONEY_FLOOR を変えた日に静かに一致しなくなり、WARN が NG に化ける）
    f"確定レンジ未満の少額表記（月{MONEY_FLOOR}万が下限）",
    "根拠なしの実績誇張",
    "他社を下げる書き方",
})


def ratio_violations(text):
    """出典なしの割合統計を検出して [(reason, hit), ...] を返す。"""
    out = []
    if not text:
        return out

    for m in DROPOUT_RATIO.finditer(text):
        window = text[max(0, m.start() - RATIO_WINDOW): m.end() + RATIO_WINDOW]
        if DROPOUT_WORD.search(window):
            out.append(("出典なしの割合統計（離脱/成功率）", window.strip()[:60]))
            break

    m = RATIO_SUBJECT.search(text)
    if m:
        out.append(("出典なしの割合統計（割合が主語を修飾）",
                    text[max(0, m.start() - 10): m.end() + 20].strip()[:60]))

    m = RATIO_PREDICATE.search(text)
    if m:
        out.append(("出典なしの割合統計（割合がそのまま述語）",
                    text[max(0, m.start() - 15): m.end() + 20].strip()[:60]))
    return out


def money_violations(text, strict=False):
    """金額表記の違反を検出して [(reason, hit), ...] を返す。

    既定（strict=False）は下限だけを見る＝月15万未満は全媒体で禁止。
    strict=True では確定レンジ（ALLOWED_MONEY）以外の「月◯万」も弾く。
    Threads は生成物をレンジ表記だけに寄せたいので strict で運用する。
    """
    if not text:
        return []
    out = []
    for m in MONEY_LOW.finditer(text):
        try:
            amount = int(m.group(1).translate(_ZEN2HAN))
        except ValueError:
            continue
        if amount < MONEY_FLOOR:
            if AGENCY_WORD.search(text[:m.start()]):
                continue  # 代理店パートナーの報酬はライバー本人の収入と別軸（確定値）
            out.append((f"確定レンジ未満の少額表記（月{MONEY_FLOOR}万が下限）", m.group(0)))
            continue
        if not strict:
            continue
        around = text[max(0, m.start() - 4): m.end() + 6]
        if not any(re.search(a, around) for a in ALLOWED_MONEY):
            out.append((f"未確定の金額表記「月{amount}万」", m.group(0)))

    # 「月収の目安: 5,000円〜3万円」のようにラベルと数字が離れている形（MONEY_LABELED）。
    # 既に MONEY_LOW で同じ箇所を報告しているものは重ねない。
    seen = {hit for _, hit in out}
    for m in MONEY_LABELED.finditer(text):
        man = _to_man(m.group(1), m.group(2))
        if man >= MONEY_FLOOR:
            continue
        if AGENCY_WORD.search(text[:m.start()]):
            continue  # 代理店パートナーの報酬は別軸（確定値）
        hit = m.group(0)
        if any(hit in s or s in hit for s in seen):
            continue
        out.append((f"確定レンジ未満の少額表記（月{MONEY_FLOOR}万が下限）", hit))
    return out


# lin.ee の短縮URLで実際に使われる文字だけを拾う。
# 旧実装は `\S+` で取って末尾を rstrip("/。、）)") していたが、これは
# **Markdown・HTMLの中では機能しない**（2026-08-12、blog/articles_note に当てて実測）:
#   - `](https://lin.ee/xchCfdn)**`      → 末尾が `*` なので rstrip の対象外
#   - `(https://lin.ee/xchCfdn)で無料で…` → 日本語が続くので `\S+` が文ごと飲み込む
# どちらも正しい公式LINEなのに「許可リスト外」と判定される（記事149本で123件の誤検知）。
# 末尾を削るのではなく **最初からURLに使える文字しか取らない** ようにして塞ぐ。
# 別ドメイン・別IDは当然ここにも合致するので、検知力は落ちない。
LINE_URL = re.compile(r"https?://lin\.ee/[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*")


def line_link_violations(text):
    """許可リスト外の公式LINEリンクを検出して [(reason, hit), ...] を返す。"""
    out = []
    for m in LINE_URL.finditer(text or ""):
        if m.group(0) != LINE_ALLOWED:
            out.append(("許可リスト外のLINEリンク", m.group(0)))
    return out


# ── 自社と矛盾する「判断軸」（2026-08-12 追加）─────────────────────
# 背景: この日、Note記事12本が「怪しい事務所の見分け方」として
#   - 「最低契約期間が1年以上」          （03_事務所選び方）
#   - 「最低契約期間が2年以上」          （29_ライバー事務所怪しい見分け方）
#   - 「一般的な契約期間: 6ヶ月〜1年 / 2年以上の長期契約は要注意」（35_契約書チェック10項目）
#   - 「契約期間が1年以上で違約金あり（辞めたくても辞められない）」（27_おすすめランキング）
# を読者に教えていたのが見つかった。**TAITAN PRO は2年契約**なので、この物差しを
# 覚えて面談に来た読者に「御社は2年ですよね？」とそのまま跳ね返る。
# 記事が自分で自分を撃つ形になっていて、しかも149本の中で誰も気づいていなかった。
#
# なぜ既存ルールで拾えなかったか:
#   COMMON_NG_PATTERNS の `違約金|契約期間` は **語が出たかどうか** しか見ておらず、
#   さらに記事側では ARTICLE_WARN_LABELS で WARN に落としてある（64箇所ある大半が
#   「違約金の有無を契約前に確認しましょう」という読者への正しい助言なので、
#   赤にすると番犬が鳴きやまない）。つまり
#     中立 「違約金の有無を確認しよう」        … 正しい。赤にしてはいけない
#     矛盾 「最低契約期間が1年以上なら悪質」   … 自社を撃つ。赤にすべき
#   の2つが同じ WARN の山に埋もれて、区別できていなかった。
#
# ここで見るのは語の有無ではなく **判断軸**。
# 935da09 で全記事を「長さ」から「明記・説明されているか」へ統一したので、
#   - 期間の長短／違約金の有無**そのもの**を良し悪しの基準にしている → 違反（赤）
#   - 条件が書面に明記・説明されているかを基準にしている             → 正しい（素通り）
# で切る。判定は**文単位**（句点・改行・箇条書き記号で切る）で、
# 同じ段落の別の文に免責語があっても効かないようにしてある。
# ラベルは定数にして各guardから参照させる。直書きすると、文言を変えた日に
# 「WARNに落ちていないこと」を検査している側と静かに一致しなくなる
# （AUDIT_WARN_LABELS が MONEY_FLOOR を式で組んでいるのと同じ理由）。
CONTRACT_AXIS_LABEL = "自社と矛盾する判断軸（契約期間の長さ・違約金の有無）"

CONTRACT_AXIS_PATTERNS = [
    # 「最低◯年」という下限の提示。長さを基準に据えた時点で自社と矛盾する
    r"最低契約期間",
    # 「契約期間が2年以上」「契約期間が1年以上で違約金あり」
    r"契約期間[がはも]?\s*[0-9０-９]+\s*(?:年|ヶ月|か月|カ月|ケ月)以上",
    # 「2年以上の長期契約は要注意」
    r"[0-9０-９]+\s*(?:年|ヶ月|か月|カ月|ケ月)以上の(?:長期)?契約",
    # 「一般的な契約期間: 6ヶ月〜1年」= 業界標準を出して自社(2年)を外れ値にする
    r"一般的な契約期間",
    # 長さを否定的に名指しする言い回し
    r"長期契約の縛り",
    r"長い拘束期間",
    r"拘束期間が長い",
    r"長い縛り",
    r"縛りが長い",
    r"長期縛り",
    # 「違約金あり＝リスク」と、有無だけで断ずる形。
    # 「違約金の有無を確認」（中立）は下の免責で外れる
    r"違約金あり",
]
CONTRACT_AXIS_RE = re.compile("|".join(CONTRACT_AXIS_PATTERNS))

# 同じ文が「明記・説明されているか」を軸にしているなら、上に当たっても素通りさせる。
# 例:「違約金や最低契約期間の有無は契約前に必ず確認を。条件を書面で明示してくれる
#     事務所が安心です」（blog/articles/liver-agency-guide.md — 935da09 後の正しい形）
# 「確認」は入れない。「『違約金あり』の事務所はリスクが大きいため契約前に必ず確認して
# ください」のような**長さ・有無で裁いたうえで確認を促す**文まで免責してしまうため。
CONTRACT_AXIS_NEUTRAL_RE = re.compile(
    r"有無|明記|明示|記載|書面|説明(?:して|が|も|は)?|きちんと(?:教え|answer)")

# 文の切れ目。句点・改行に加えて、表のセル（|）と **HTMLタグの境界** でも切る。
# タグを切れ目に入れるのは、note からエクスポートした記事が1行に
# `<li><p ...>一般的な契約期間: 6ヶ月〜1年</p></li><li><p ...>2年以上の長期契約は要注意</p></li>`
# のように全部を詰め込んでくるため（35_ライバー事務所契約書チェック10項目 が実際この形）。
# 句点だけで切ると、無関係な隣のセルにある「明記」を免責語として拾って
# 見逃す side がある。タグ境界で切っておけば1項目=1文になる。
_SENTENCE_SPLIT_RE = re.compile(r"[。！？!?\n]|\||<[^>]*>")


def contract_axis_violations(text):
    """自社と矛盾する判断軸を検出して [(reason, hit), ...] を返す。

    語の出現ではなく「契約期間の長さ・違約金の有無そのものを良し悪しの基準に
    しているか」を見る。同じ文が明記・説明を基準にしていれば素通りさせる。
    """
    if not text:
        return []
    out = []
    for sentence in _SENTENCE_SPLIT_RE.split(text):
        m = CONTRACT_AXIS_RE.search(sentence)
        if not m:
            continue
        if CONTRACT_AXIS_NEUTRAL_RE.search(sentence):
            continue
        # 当たった語そのものが見えるように、マッチ位置を中心に切り出す。
        # 文頭から80字だと、HTML属性やMarkdown記法で肝心の語が画面外に出る。
        s, e = max(0, m.start() - 25), min(len(sentence), m.end() + 45)
        hit = ("…" if s else "") + sentence[s:e].strip() + ("…" if e < len(sentence) else "")
        out.append((CONTRACT_AXIS_LABEL, hit))
    return out


def ng_violations(text, patterns=None):
    """禁止パターンを当てて [(reason, hit), ...] を返す。

    生テキストに加えて、空白を全部詰めた文字列にも当てる。
    「9 割」「手　数　料」のように空白を挟むだけで検品を抜けられるのを塞ぐため
    （もともとXにしか無かった処理。共通化してThreadsにも効かせる）。
    """
    if not text:
        return []
    if patterns is None:
        patterns = COMMON_NG_PATTERNS
    flat = re.sub(r"\s+", "", text)
    out = []
    for pat, label in patterns:
        m = re.search(pat, text) or re.search(pat, flat)
        if m:
            out.append((label, m.group(0)[:40]))
    return out


def common_violations(text, extra_patterns=(), strict_money=False):
    """媒体共通の確定ファクト検品。[(reason, hit), ...] を返す。

    各媒体の guard はこれを呼び、自分の媒体でしか意味がないルール
    （文字数上限・宣伝密度など）だけを自前で足す。
    extra_patterns には媒体固有の (pattern, label) を渡せる。
    """
    if not text:
        return []
    flat = re.sub(r"\s+", "", text)
    out = ng_violations(text, list(COMMON_NG_PATTERNS) + list(extra_patterns))
    out += ratio_violations(text) or ratio_violations(flat)
    out += money_violations(text, strict=strict_money)
    out += line_link_violations(text)
    # 判断軸の矛盾。ng_violations と違い**文単位で全件**返す（1本の記事の
    # 危険サインチェックリストに複数並ぶのが実際の形なので、1件で打ち切らない）。
    out += contract_axis_violations(text)
    return out
