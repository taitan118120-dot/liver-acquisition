def _targets(only):
    ids = list(WARN_REPLACEMENTS) + LISTENER_ONLY
    if not only:
        return ids
    missing = [p for p in only if p not in ids]
    if missing:
        raise SystemExit(f"対象外のID: {missing}")
    return only


def full_rules(post_id):
    """RED修正（あれば）→ このスクリプトのWARN修正、の順に連結する。"""
    return red_fix.REPLACEMENTS.get(post_id, []) + WARN_REPLACEMENTS.get(post_id, [])


def leftovers(text, post_id=None):
    words = list(_MONEY_LEFTOVERS)
    if post_id:
        words += LEFTOVERS_BY_POST.get(post_id, [])
    return [w for w in words if w in text]


def show(only):
    posts = load_posts()
    for post_id in _targets(only):
        _, post = find_post(posts, post_id)
        new, missed = transform(post["caption"], full_rules(post_id))
        print("=" * 70)
        print(f"{post_id}  media_id={post.get('media_id')}  "
              f"元記事={post.get('source_file')}")
        print("=" * 70)
        if missed:
            print(f"  !! 置換元が見つからない: {missed}")
            print("     （キャプションが既に手で変わっている可能性。"
                  "差分を確認してから直すこと）")
            continue
        if new == post["caption"]:
            print("  変更なし（既に適用済み）\n")
            continue
        print("\n【今の違反】")
        for r, h in violations(post["caption"]):
            print(f"  - {r} | {h[:70]}")
        print("\n【直したあとの違反】")
        after = violations(new)
        for r, h in after:
            print(f"  - {r} | {h[:70]}")
        if not after:
            print("  なし")
        print(f"  残存NGワード: {leftovers(new, post_id) or 'なし'}")
        print(f"\n───── 貼り付け用キャプション全文（{len(new)}文字）─────")
        print(new)
        print("───── ここまで ─────\n")


def apply(only):
    posts = load_posts()
    changed = 0
    for post_id in _targets(only):
        i, post = find_post(posts, post_id)
        new, missed = transform(post["caption"], full_rules(post_id))
        if missed:
            raise RuntimeError(f"{post_id}: 置換元が見つからない {missed}")
        if new == post["caption"]:
            print(f"  {post_id} 変更なし（既に適用済み）")
            continue
        left = leftovers(new, post_id)
        if left:
            raise RuntimeError(f"{post_id}: 置換後にNGワードが残っている {left}")
        old_len = len(post["caption"])
        posts[i]["caption"] = new
        posts[i]["caption_edited_at"] = "2026-09-05"
        posts[i]["caption_edit_reason"] = (
            "少額表記・断定表現・呼び捨てなどWARN対象だった記述をユーザー判断で"
            "修正（Instagramアプリでの手編集と同期）")
        changed += 1
        print(f"  {post_id} 更新（{old_len} -> {len(new)}文字）")
    if changed:
        with open(POSTS_FILE, "w", encoding="utf-8") as f:
            json.dump(posts, f, ensure_ascii=False, indent=2)
        print(f"\nig_posts.json を更新（{changed}件）")
    return changed


def check(only):
    """ig_posts.json 側の現状を検品する（貼り替え漏れの確認用）。"""
    posts = load_posts()
    bad = 0
    for post_id in _targets(only):
        _, post = find_post(posts, post_id)
        v = violations(post["caption"])
        left = leftovers(post["caption"], post_id)
        mark = "OK " if not (v or left) else "NG "
        print(f"  {mark}{post_id}: 違反={len(v)} 残存={left or 'なし'}")
        bad += bool(v or left)
    print(f"\n未処理 {bad} / {len(_targets(only))} 件")
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--show", action="store_true",
                    help="貼り付け用キャプション全文を出す（既定）")
    ap.add_argument("--apply", action="store_true",
                    help="ig_posts.json を新しい文面に更新（アプリで貼り替えた後に実行）")
    ap.add_argument("--check", action="store_true",
                    help="ig_posts.json 側の残りを一覧する")
    ap.add_argument("--only", nargs="*", default=None,
                    help="対象の投稿IDを絞る（例: --only ig_auto_017 ig_auto_045）")
    args = ap.parse_args()

    if args.apply:
        return 0 if apply(args.only) is not None else 1
    if args.check:
        return 1 if check(args.only) else 0
    show(args.only)
    return 0


if __name__ == "__main__":
    sys.exit(main())
